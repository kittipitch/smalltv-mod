#!/usr/bin/env python3
"""Generate a PROGMEM cell-logo header from a grid JSON (see gen_agy_logo.py).

Usage: gen_cell_logo.py <grid.json> <out-header.h> <ARRAY_NAME>
Same byte format as AgyLogo.h: one RGB byte triple per cell, all-zero = transparent,
pgm_read_byte only."""
import json
import sys
from pathlib import Path

grid = json.load(open(sys.argv[1]))
cols, rows, cells = grid["cols"], grid["rows"], grid["cells"]
assert len(cells) == rows and all(len(r) == cols for r in cells)
name = sys.argv[3]
flat = []
for r in cells:
    for c in r:
        flat += ([0, 0, 0] if c is None else [max(1, v) for v in c])  # a real cell is never all-zero
lines = ["" .join("  " + ", ".join(f"0x{v:02X}" for v in flat[i:i + 12]) + "," ) for i in range(0, len(flat), 12)]
out = f"""// {Path(sys.argv[2]).name} -- generated by scripts/gen_cell_logo.py, do not edit by hand.
// A {cols}x{rows} grid of colour cells (pixel logo), one RGB byte triple per cell, row by row; an
// all-zero triple is transparent. Bytes in PROGMEM, read with pgm_read_byte only (never a uint16_t
// PROGMEM array: pgm_read_word once crash-looped a unit).
#pragma once
#include <Arduino.h>

#define {name}_COLS {cols}
#define {name}_ROWS {rows}

static const uint8_t k{name}[{name}_COLS * {name}_ROWS * 3] PROGMEM = {{
{chr(10).join(lines)}
}};
"""
Path(sys.argv[2]).write_text(out)
print(sys.argv[2], len(flat), "bytes")
