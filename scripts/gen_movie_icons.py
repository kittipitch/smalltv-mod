#!/usr/bin/env python3
"""Bake the Movies page icons (Twemoji 15.1, CC-BY 4.0) into RGB565 PROGMEM arrays.

The PNGs in tools/movie_icons/ are the 72x72 Twemoji assets
(https://github.com/jdecked/twemoji, graphics licensed CC-BY 4.0). Each is downscaled to
SIZE px and composited over the card colour, so the device draws an opaque block with no
alpha work. Run from the repo root:  python3 scripts/gen_movie_icons.py
"""
from pathlib import Path
from PIL import Image

SIZE = 28
PANEL = 0x18E3                      # C_PANEL in MoviesMode.cpp
ICONS = [("kIconTomato", "1f345"), ("kIconPopcorn", "1f37f"), ("kIconFilm", "1f3ac"), ("kIconTv", "1f4fa")]
root = Path(__file__).resolve().parents[1]
src = root / "tools/movie_icons"
out = root / "src/features/movies/MovieIcons.h"

bg = (((PANEL >> 11) & 31) * 255 // 31, ((PANEL >> 5) & 63) * 255 // 63, (PANEL & 31) * 255 // 31)
lines = ["// MovieIcons.h -- generated by scripts/gen_movie_icons.py, do not edit.",
         "// Twemoji 15.1 by Twitter/X and contributors, CC-BY 4.0 (https://github.com/jdecked/twemoji).",
         "#pragma once", "#include <Arduino.h>", f"#define MOVIE_ICON_PX {SIZE}"]
for name, code in ICONS:
    im = Image.open(src / f"{code}.png").convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    flat = Image.new("RGBA", im.size, bg + (255,))
    flat.alpha_composite(im)
    px = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b, _ in flat.get_flattened_data()]
    rows = [", ".join(f"0x{v:04X}" for v in px[i:i + SIZE // 2]) for i in range(0, len(px), SIZE // 2)]
    lines.append(f"static const uint16_t {name}[{SIZE * SIZE}] PROGMEM = {{  // U+{code.upper()}")
    lines += ["  " + r + "," for r in rows]
    lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out.relative_to(root)}")
