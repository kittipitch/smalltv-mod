#!/usr/bin/env python3
"""Generate src/features/calendar/AgyLogo.h from a cell-grid JSON.

Usage: python3 scripts/gen_agy_logo.py <grid.json>
The JSON is {"cols": C, "rows": R, "cells": [[[r,g,b] | null, ...], ...]}; null is background.
Output is one RGB triple per cell in PROGMEM as plain bytes (read them with pgm_read_byte only: a
uint16_t PROGMEM array read with pgm_read_word once crash-looped a unit). An all-zero triple means
"transparent"; the grid is rejected if a real cell is pure black.
"""
import json
import sys
from pathlib import Path

grid = json.load(open(sys.argv[1]))
cols, rows, cells = grid["cols"], grid["rows"], grid["cells"]
assert len(cells) == rows and all(len(r) == cols for r in cells)
flat = []
for r in cells:
    for c in r:
        if c is None:
            flat += [0, 0, 0]
        else:
            assert any(c), "a real cell must not be pure black (it is the transparent marker)"
            flat += c
lines = []
for i in range(0, len(flat), 12):
    lines.append("  " + ", ".join(f"0x{v:02X}" for v in flat[i:i + 12]) + ",")
out = f"""// AgyLogo.h -- generated by scripts/gen_agy_logo.py, do not edit by hand.
// The Antigravity header logo: a {cols}x{rows} grid of colour cells (pixel art, rainbow), one RGB byte
// triple per cell, row by row; an all-zero triple is transparent. Bytes in PROGMEM, read with
// pgm_read_byte only (never a uint16_t PROGMEM array: pgm_read_word once crash-looped a unit).
#pragma once
#include <Arduino.h>

#define AGY_LOGO_COLS {cols}
#define AGY_LOGO_ROWS {rows}

static const uint8_t kAgyLogo[AGY_LOGO_COLS * AGY_LOGO_ROWS * 3] PROGMEM = {{
{chr(10).join(lines)}
}};
"""
dest = Path(__file__).resolve().parents[1] / "src/features/calendar/AgyLogo.h"
dest.write_text(out)
print(dest, len(flat), "bytes")
